assert.equal(data.x86_instructions.length,32);
assert.equal(data.priority.length,15);
for (const title of data.priority) assert(data.items.some(x=>x.title===title));
for(const item of data.items) for(const field of ['core','detail','example','trap']) assert(item[field].length>15,`${item.title}: ${field}`);
