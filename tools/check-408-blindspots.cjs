const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const {branchImmediate} = require('../js/408-blindspots-extras.js');
const core = require('../js/408-blindspots.js');
const example = branchImmediate('0x00400020', '0x00400010');
assert.equal(example.immediate,-5); assert.equal(example.encoding,'0xFFFB');
